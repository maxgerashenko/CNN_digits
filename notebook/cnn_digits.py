"""# Model"""

import tensorflow as tf
import numpy as np
import random

# Shape
(_, WIDTH, HEIGHT, CHANNELS) = train_normalized_shaped.shape

# Hyperparameters
KERNEL_SIZE = 3
POOLING_SIZE = 2
STRIDE_POOLING = 2
STRIDE_CONVOLUTION = 1

FIRST_LAYER_FILTERS = 16
SECOND_LAYER_FILTERS = 32

PADDING = 'same'
FULLY_CONNECTED_UNITS = 128
LEARNING_DROPOUT = 0.1
OUTPUT_UNITS = 10

BATCH_SIZE = 32
LEARNING_RATE = 0.001

SEED = 42
tf.keras.utils.set_random_seed(SEED)

np.random.seed(SEED)
random.seed(SEED)

# Helper block: Conv -> BatchNormal -> ReLU
def conv_bn_relu(filters, kernel_size, strides=1, padding='same'):
    return [
        tf.keras.layers.Conv2D(
            filters=filters,
            kernel_size=kernel_size,
            strides=strides,
            padding=padding,
            activation=None,
            use_bias=False,
            # kernel_initializer=tf.keras.initializers.VarianceScaling()
            kernel_initializer=tf.keras.initializers.HeNormal()
        ),
        tf.keras.layers.BatchNormalization(),
        tf.keras.layers.Activation('relu')
    ]

DATA_AUGMENTATION_ANGLE = 0.05

# tilting the input a littl ebit
data_augmentation = tf.keras.Sequential([
    tf.keras.layers.RandomRotation(DATA_AUGMENTATION_ANGLE),
    tf.keras.layers.RandomZoom(DATA_AUGMENTATION_ANGLE),
    tf.keras.layers.RandomTranslation(DATA_AUGMENTATION_ANGLE, DATA_AUGMENTATION_ANGLE),
])

# Build model
# Wrap the entire model construction in a CPU device context to avoid potential GPU initialization issues.
model = tf.keras.Sequential([
    tf.keras.layers.Input(shape=(WIDTH, HEIGHT, CHANNELS)),

    data_augmentation,

    # Block 1
    *conv_bn_relu(FIRST_LAYER_FILTERS, KERNEL_SIZE, STRIDE_CONVOLUTION, PADDING),
    *conv_bn_relu(FIRST_LAYER_FILTERS, KERNEL_SIZE, STRIDE_CONVOLUTION, PADDING),
    tf.keras.layers.MaxPooling2D(
        pool_size=(POOLING_SIZE, POOLING_SIZE),
        strides=(STRIDE_POOLING, STRIDE_POOLING)
    ),

    # Block 2
    *conv_bn_relu(SECOND_LAYER_FILTERS, KERNEL_SIZE, STRIDE_CONVOLUTION, PADDING),
    *conv_bn_relu(SECOND_LAYER_FILTERS, KERNEL_SIZE, STRIDE_CONVOLUTION, PADDING),
    tf.keras.layers.MaxPooling2D(
        pool_size=(POOLING_SIZE, POOLING_SIZE),
        strides=(STRIDE_POOLING, STRIDE_POOLING)
    ),

    # Head
    tf.keras.layers.Flatten(),
    # tf.keras.layers.GlobalAveragePooling2D(),


    tf.keras.layers.Dense(
        FULLY_CONNECTED_UNITS,
        activation=None,
        use_bias=False,
        kernel_initializer=tf.keras.initializers.VarianceScaling()
    ),
    tf.keras.layers.BatchNormalization(),
    tf.keras.layers.Activation('relu'),

    tf.keras.layers.Dropout(LEARNING_DROPOUT),

    tf.keras.layers.Dense(
        OUTPUT_UNITS,
        activation='softmax'
    )
])

# Compile
# Wrap model compilation in a CPU device context to avoid potential GPU initialization issues with the optimizer.
model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=LEARNING_RATE),
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

# Summary
model.summary()

